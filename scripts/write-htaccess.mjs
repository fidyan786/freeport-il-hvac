/**
 * Writes public/.htaccess from src/lib/legacy-redirects.ts so Apache rules
 * cannot drift from the redirect list. Hostinger shared hosting is LiteSpeed
 * or Apache; this file is copied into the static export.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const source = readFileSync(
  path.join(root, "src/lib/legacy-redirects.ts"),
  "utf8",
);
const pairs = [...source.matchAll(/\["(\/[^"]*)", "(\/[^"]*)"\]/g)].map(
  (match) => [match[1], match[2]],
);

if (pairs.length < 40) {
  console.error(`write-htaccess: expected legacy redirects, found ${pairs.length}`);
  process.exit(1);
}

const APEX = "https://freeporthvacil.com";

function absoluteDest(destination) {
  if (destination === "/") return `${APEX}/`;
  const withSlash = destination.endsWith("/") ? destination : `${destination}/`;
  return `${APEX}${withSlash}`;
}

const legacyRules = pairs
  .map(([from, to]) => {
    const bare = from.replace(/^\//, "").replace(/\/$/, "");
    return `RewriteRule ^${bare}/?$ ${absoluteDest(to)} [R=301,L,NC]`;
  })
  .join("\n");

const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "style-src 'self' 'unsafe-inline'",
  "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://www.google-analytics.com",
  "connect-src 'self' https://www.google-analytics.com https://www.googletagmanager.com https://analytics.google.com https://stats.g.doubleclick.net",
  "worker-src 'self' blob:",
  "upgrade-insecure-requests",
].join("; ");

const htaccess = `# Generated by scripts/write-htaccess.mjs. Do not edit by hand.
# Hostinger shared hosting (Apache or LiteSpeed). Static files live in public_html.
Options -Indexes -MultiViews
DirectoryIndex index.html

ErrorDocument 404 /404.html

<FilesMatch "^(icon|apple-icon|opengraph-image)$">
  ForceType image/png
</FilesMatch>

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains; preload"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "DENY"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=(), browsing-topics=()"
  Header always set X-DNS-Prefetch-Control "off"
</IfModule>

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Extensionless Next image routes are real PNG files. Map the trailing-slash URL onto the file.
  RewriteRule ^((?:.*/)?)(opengraph-image|apple-icon|icon)/$ /$1$2 [L]

  # Old URLs, either slash form, any host or scheme: one hop to the https apex.
  # NC folds uppercase variants into the same lowercase destination.
${legacyRules}

  # www to the apex, on either scheme.
  RewriteCond %{HTTP_HOST} ^www\\.freeporthvacil\\.com$ [NC]
  RewriteRule ^ ${APEX}%{REQUEST_URI} [R=301,L]

  # Plain http to https. Skip when Hostinger already terminated TLS.
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ ${APEX}%{REQUEST_URI} [R=301,L]

  # Trailing slash for pages. Real files (sitemap, robots, images, 404.html) stay put.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_URI} !/$
  RewriteCond %{REQUEST_URI} !\\.[A-Za-z0-9]{1,5}$
  RewriteRule ^(.+)$ ${APEX}/$1/ [R=301,L]
</IfModule>
`;

writeFileSync(path.join(root, "public/.htaccess"), htaccess);
console.log(`write-htaccess: ${pairs.length} legacy rules`);

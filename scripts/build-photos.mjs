/**
 * Builds 3:2 WebP masters plus 480/640/960 WebP and AVIF derivatives.
 * Sources already in public/photos/*.webp are re-encoded.
 * New Commons downloads are listed in INCOMING.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const photoDir = path.join(root, "public/photos");
const heroDir = path.join(photoDir, "heroes");
const sizedDir = path.join(photoDir, "sized");
const UA = "FreeportHVACResearch/1.0 (static site; image credits)";

const INCOMING = [
  ["condenser-beside-house", "File:Condenser unit for central air conditioning.JPG"],
  [
    "aging-split-condenser",
    "File:Aging Condenser Unit of a Split Air Conditioning System (7547606426).jpg",
  ],
  ["wall-mounted-condenser", "File:Wall mounted air conditioning condenser.jpg"],
  ["touch-thermostat", "File:A touch-screen programmable thermostat.jpg"],
  ["basement-sheet-metal-ducts", "File:Ottawa marriott basement ductwork.jpg"],
  ["condensing-furnace-vent", "File:Condensing Furnace Outlet.jpg"],
  ["dahinda-illinois-farmhouse", "File:Farmhouse near Dahinda Illinois USA.jpg"],
  ["yerkes-house-oak-park-snow", "File:Yerkes House In the Snow.JPG"],
];

async function download(title) {
  const file = title.split(":").slice(1).join(":");
  const url =
    "https://commons.wikimedia.org/wiki/Special:FilePath/" +
    encodeURIComponent(file) +
    "?width=1600";
  const response = await fetch(url, { headers: { "User-Agent": UA }, redirect: "follow" });
  if (!response.ok) throw new Error(`${response.status} ${title}`);
  return Buffer.from(await response.arrayBuffer());
}

async function masterFrom(input) {
  return sharp(input)
    .rotate()
    .resize(1200, 800, { fit: "cover", position: "centre" })
    .webp({ quality: 68 })
    .toBuffer();
}

async function emitSizes(name, master) {
  const meta = await sharp(master).metadata();
  const sourceWidth = meta.width ?? 1200;
  const widths = [480, 640, 960].filter((width) => width <= sourceWidth);
  if (!widths.length) widths.push(Math.min(480, sourceWidth));
  for (const width of widths) {
    const height = Math.round((width * 2) / 3);
    const pipeline = sharp(master).resize(width, height, { fit: "cover" });
    await pipeline.clone().webp({ quality: 62 }).toFile(path.join(sizedDir, `${name}-${width}.webp`));
    await pipeline.clone().avif({ quality: 45 }).toFile(path.join(sizedDir, `${name}-${width}.avif`));
  }
  await sharp(master)
    .resize(640, 427, { fit: "cover" })
    .webp({ quality: 60 })
    .toFile(path.join(heroDir, `${name}.webp`));
  return widths;
}

const sizes = {};
await mkdir(heroDir, { recursive: true });
await mkdir(sizedDir, { recursive: true });

for (const [name, title] of INCOMING) {
  process.stdout.write(`download ${name}\n`);
  const bytes = await download(title);
  const master = await masterFrom(bytes);
  await writeFile(path.join(photoDir, `${name}.webp`), master);
  sizes[name] = await emitSizes(name, master);
}

const existing = (await readdir(photoDir)).filter(
  (file) => file.endsWith(".webp") && !INCOMING.some(([name]) => file === `${name}.webp`),
);
for (const file of existing) {
  const name = file.replace(/\.webp$/, "");
  const master = await readFile(path.join(photoDir, file));
  sizes[name] = await emitSizes(name, master);
  process.stdout.write(`sized ${name} ${sizes[name].join(",")}\n`);
}

const lines = [
  "/** Pixel widths emitted for each photograph. Generated by scripts/build-photos.mjs. */",
  "export const PHOTO_WIDTHS: Record<string, number[]> = {",
  ...Object.keys(sizes)
    .sort()
    .map((name) => `  "${name}": [${sizes[name].join(", ")}],`),
  "};",
  "",
];
await writeFile(path.join(root, "src/lib/photo-sizes.ts"), lines.join("\n"));
console.log(`build-photos: ${Object.keys(sizes).length} photographs`);
